/** DAY / NIGHT canteen of an area, or NONE (neither serves). */
export const areaTargetSchema = z.enum(['DAY', 'NIGHT', 'NONE']);
const clockTime = z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/);
const serviceHours = z.strictObject({ opensAt: clockTime, closesAt: clockTime }).nullable();
/** Day/Night hours of an area, local to `timezone` (IANA, default Asia/Kolkata). */
export const areaScheduleSchema = z.strictObject({
  autoSwitchEnabled: z.boolean(),
  timezone: z.string(),
  day: serviceHours,
  night: serviceHours,
});

/** Admin service area (`GET /api/admin/service-areas`). */
export const serviceAreaSchema = z.strictObject({
  id: uuid,
  name: z.string(),
  hostels: z.array(z.strictObject({ id: uuid, name: z.string(), isActive: z.boolean() })),
  canteens: z.array(canteenSchema),
  /** The canteen on duty for this area, or null when neither is. */
  openCanteenId: uuid.nullable(),
  schedule: areaScheduleSchema,
  /**
   * AUTOMATIC        follows the schedule
   * MANUAL_OVERRIDE  an admin's manual choice overrides the schedule for now
   * MANUAL           automatic switching is off; admins switch by hand
   */
  mode: z.enum(['AUTOMATIC', 'MANUAL_OVERRIDE', 'MANUAL']),
  /** What the schedule alone wants now (null when automatic switching is off). */
  scheduledTarget: areaTargetSchema.nullable(),
  override: z
    .strictObject({ target: areaTargetSchema, until: isoDate.nullable(), setAt: isoDate })
    .nullable(),
  /** Next scheduled change (null when automatic switching is off). */
  nextTransition: z.strictObject({ at: isoDate, target: areaTargetSchema }).nullable(),
});

